export function getProductById(id: string): Product | undefined {
  return products.find((p) => p.id === id)
}

export function getProductsByCategory(category: string): Product[] {
  return products.filter((p) => p.category.toLowerCase().replace(/\s+/g, '-') === category.toLowerCase() || p.category === category)
}

export function getBestSellers(): Product[] {
  return products.filter((p) => p.badge === 'bestseller')
}

export function getNewArrivals(): Product[] {
  return products.filter((p) => p.badge === 'new')
}

export function getTrendingProducts(): Product[] {
  return products.filter((p) => p.badge === 'trending')
}

export function getSaleProducts(): Product[] {
  return products.filter((p) => p.badge === 'sale')
}

export function getRelatedProducts(productId: string, limit: number = 4): Product[] {
  const product = getProductById(productId)
  if (!product) return []
  
  return products
    .filter((p) => p.category === product.category && p.id !== productId)
    .slice(0, limit)
}

export function searchProducts(query: string): Product[] {
  const lowercaseQuery = query.toLowerCase()
  return products.filter(
    (p) =>
      p.name.toLowerCase().includes(lowercaseQuery) ||
      p.description.toLowerCase().includes(lowercaseQuery) ||
      p.category.toLowerCase().includes(lowercaseQuery)
  )
}

export function filterProducts(options: {
  category?: string
  minPrice?: number
  maxPrice?: number
  sortBy?: 'price-asc' | 'price-desc' | 'rating' | 'newest'
  inStock?: boolean
}): Product[] {
  let filtered = [...products]

  if (options.category) {
    filtered = filtered.filter((p) => p.category.toLowerCase().replace(/\s+/g, '-') === options.category?.toLowerCase())
  }

  if (options.minPrice !== undefined) {
    filtered = filtered.filter((p) => p.price >= options.minPrice!)
  }

  if (options.maxPrice !== undefined) {
    filtered = filtered.filter((p) => p.price <= options.maxPrice!)
  }

  if (options.inStock) {
    filtered = filtered.filter((p) => p.inStock)
  }

  if (options.sortBy) {
    switch (options.sortBy) {
      case 'price-asc':
        filtered.sort((a, b) => a.price - b.price)
        break
      case 'price-desc':
        filtered.sort((a, b) => b.price - a.price)
        break
      case 'rating':
        filtered.sort((a, b) => b.rating - a.rating)
        break
      case 'newest':
        filtered = filtered.filter((p) => p.badge === 'new').concat(filtered.filter((p) => p.badge !== 'new'))
        break
    }
  }

  return filtered
}
